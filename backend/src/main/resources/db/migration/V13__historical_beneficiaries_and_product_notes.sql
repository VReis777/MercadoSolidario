CREATE TABLE historical_beneficiaries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_year INTEGER NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    normalized_name VARCHAR(255) NOT NULL,
    cpf VARCHAR(11),
    phone VARCHAR(20),
    address VARCHAR(500),
    household_size INTEGER,
    origin VARCHAR(255),
    source_file VARCHAR(255) NOT NULL,
    source_sheet VARCHAR(100),
    source_row INTEGER,
    imported_by VARCHAR(100),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_historical_beneficiaries_year ON historical_beneficiaries(campaign_year);
CREATE INDEX idx_historical_beneficiaries_cpf ON historical_beneficiaries(cpf);
CREATE INDEX idx_historical_beneficiaries_name ON historical_beneficiaries(normalized_name);

