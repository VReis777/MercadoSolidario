CREATE TABLE user_password_setup_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    used_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_user_password_setup_token_user UNIQUE (user_id),
    CONSTRAINT uq_user_password_setup_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_user_password_setup_token_user
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX idx_user_password_setup_tokens_expires_at
    ON user_password_setup_tokens(expires_at);
